export function getRandomCommit(category: string): string {
  const list =
    category === 'mix'
      ? Object.values(COMMIT_MESSAGES).flat()
      : COMMIT_MESSAGES[category] || COMMIT_MESSAGES.conventional;
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}
